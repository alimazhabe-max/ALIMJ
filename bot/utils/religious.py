def religious_countdown() -> str:
    """نزدیک‌ترین مناسبت‌های مذهبی قمری"""
    try:
        today_g = datetime.now(tehran_tz).date()
        adj = today_g - timedelta(days=1)
        h = Gregorian(adj.year, adj.month, adj.day).to_hijri()
        hy, hm, hd = h.year, h.month, h.day

        upcoming = []
        for em, ed, name in RELIGIOUS_EVENTS:
            # امسال قمری
            try:
                target_h = Hijri(hy, em, min(ed, 28))
                if (em, ed) < (hm, hd):
                    target_h = Hijri(hy + 1, em, min(ed, 28))
                tg = target_h.to_gregorian()
                tg_date = date(tg.year, tg.month, tg.day)
                days = (tg_date - today_g).days
                if 0 <= days <= 90:
                    upcoming.append((days, name, em, ed))
            except Exception:
                continue

        upcoming.sort(key=lambda x: x[0])
        if not upcoming:
            return "📅 مناسبت نزدیکی در ۹۰ روز آینده ثبت نشده."

        lines = ["🕌 **شمارش‌معکوس مناسبت‌های مذهبی**\n"]
        for days, name, em, ed in upcoming[:6]:
            if days == 0:
                lines.append(f"🎉 امروز: **{name}**")
            else:
                lines.append(f"• {name}: **{pn(days)} روز** مانده")
        return "\n".join(lines)
    except Exception as e:
        return f"❌ خطا در محاسبه: {e}"
